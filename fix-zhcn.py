import io

p = r'D:\CODEX\WEB\ai-cloner\src\components\sites\vutu\locales\zh-CN.ts'
s = io.open(p, encoding='utf-8').read()

# traditional -> simplified inside zh-CN only
FIX = [
    ('體驗', '体验'), ('虛擬', '虚拟'), ('語音', '语音'), ('影片', '视频'),
    ('圖像', '图像'), ('編輯', '编辑'), ('畫布', '画布'), ('創作', '创作'),
    ('藝術', '艺术'), ('時間', '时间'), ('風格', '风格'), ('內容', '内容'),
    ('網絡', '网络'), ('鏈接', '链接'), ('點擊', '点击'), ('設置', '设置'),
    ('數據', '数据'), ('資訊', '信息'), ('支援', '支持'), ('聯絡', '联系'),
    ('選單', '菜单'), ('頁面', '页面'), ('開始', '开始'), ('過程', '过程'),
    ('產品', '产品'), ('團隊', '团队'), ('專業', '专业'), ('廣告', '广告'),
    ('動畫', '动画'), ('過渡', '过渡'), ('這個', '这个'), ('貨幣', '货币'),
    ('講', '讲'), ('構', '构'), ('價', '价'), ('後', '后'), ('與', '与'),
]

n = 0
for a, b in FIX:
    if a in s:
        n += s.count(a)
        s = s.replace(a, b)

io.open(p, 'w', encoding='utf-8').write(s)
print('zh-CN traditional chars fixed:', n)
